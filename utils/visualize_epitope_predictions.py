import config


def load_protein_data(pdb_id):
    """Load protein data from the structured dataset."""
    with open(config.STRUCTURED_DATA_PATH, 'rb') as f:
        protein_data_list = pickle.load(f)
    
    for protein_data in protein_data_list:
        if protein_data['pdb_id'].lower() == pdb_id.lower():
            return protein_data
    
    return None


def get_predictions(protein_data, model_path=None):
    """Run the XGBoost model to get predictions."""
    if model_path is None:
        model_path = config.FINAL_MODEL_PATH
    
    model = xgb.XGBClassifier()
    model.load_model(model_path)
    
    X = protein_data['X_arr']
    pred_probas = model.predict_proba(X)[:, 1]
    
    return pred_probas


def create_pymol_script(df_stats, pdb_id, chain_id, output_path, local_pdb=None):
    """
    Generate a comprehensive PyMOL script for visualization.
    """
    pdb_source = f'fetch {pdb_id}, async=0' if local_pdb is None else f'load {local_pdb}'
    
    script = f'''# =========================================================================
# Epitope Prediction Visualization - PyMOL Script
# PDB: {pdb_id.upper()}, Chain: {chain_id}
# Generated by visualize_epitope_predictions.py
# =========================================================================

# --- LOAD STRUCTURE ---
reinitialize
{pdb_source}
remove solvent
remove hetatm

# --- SETUP ---
bg_color white
set cartoon_fancy_helices, 1
set cartoon_smooth_loops, 1
set cartoon_loop_radius, 0.3
set ray_shadows, 0
set antialias, 2

# --- BASE REPRESENTATION ---
hide everything
show cartoon, chain {chain_id}
color gray80, chain {chain_id}

# =========================================================================
# COLOR BY PREDICTION SCORE
# =========================================================================

'''
    
    # Define color thresholds
    thresholds = [
        (0.8, 'firebrick', 'Very High (>= 0.8)'),
        (0.7, 'red', 'High (0.7-0.8)'),
        (0.6, 'orange', 'Medium-High (0.6-0.7)'),
        (0.5, 'yellow', 'Medium (0.5-0.6)'),
        (0.4, 'palegreen', 'Low-Medium (0.4-0.5)'),
        (0.3, 'lightblue', 'Low (0.3-0.4)'),
    ]
    
    for i, (thresh, color, label) in enumerate(thresholds):
        if i == 0:
            mask = df_stats['prediction_score'] >= thresh
        else:
            prev_thresh = thresholds[i-1][0]
            mask = (df_stats['prediction_score'] >= thresh) & (df_stats['prediction_score'] < prev_thresh)
        
        residues = df_stats[mask]['res_id'].tolist()
        if residues:
            res_str = '+'.join([str(r).strip() for r in residues])
            sel_name = f"pred_{color}"
            script += f"# {label}: {len(residues)} residues\n"
            script += f"select {sel_name}, chain {chain_id} and resi {res_str}\n"
            script += f"color {color}, {sel_name}\n\n"

    # High confidence predictions - show as sticks
    high_conf = df_stats[df_stats['prediction_score'] >= 0.6]['res_id'].tolist()
    if high_conf:
        res_str = '+'.join([str(r).strip() for r in high_conf])
        script += f'''
# --- HIGHLIGHT HIGH CONFIDENCE PREDICTIONS ---
select high_confidence, chain {chain_id} and resi {res_str}
show sticks, high_confidence and not name c+n+o
set stick_radius, 0.15, high_confidence

'''

    # Ground truth epitopes
    gt_epitopes = df_stats[df_stats['is_epitope'] == 1]['res_id'].tolist()
    if gt_epitopes:
        res_str = '+'.join([str(r).strip() for r in gt_epitopes])
        script += f'''
# --- GROUND TRUTH EPITOPES (labeled in dataset) ---
# Uncomment lines below to visualize ground truth
select ground_truth, chain {chain_id} and resi {res_str}
# show spheres, ground_truth and name CA
# color forest, ground_truth
# set sphere_scale, 0.5, ground_truth

'''

    # Add statistics
    total = len(df_stats)
    gt_count = df_stats['is_epitope'].sum()
    pred_high = (df_stats['prediction_score'] >= 0.6).sum()
    pred_med = ((df_stats['prediction_score'] >= 0.5) & (df_stats['prediction_score'] < 0.6)).sum()
    
    script += f'''
# =========================================================================
# STATISTICS
# =========================================================================
# Total residues: {total}
# Ground truth epitopes: {gt_count} ({100*gt_count/total:.1f}%)
# Predicted high confidence (>= 0.6): {pred_high} ({100*pred_high/total:.1f}%)
# Predicted medium confidence (0.5-0.6): {pred_med} ({100*pred_med/total:.1f}%)

# =========================================================================
# FINALIZE VIEW
# =========================================================================
deselect
orient chain {chain_id}
zoom chain {chain_id}
center chain {chain_id}

# Show surface with transparency (optional)
# show surface, chain {chain_id}
# set transparency, 0.7, chain {chain_id}

# =========================================================================
# RENDER AND SAVE
# =========================================================================
set ray_opaque_background, 1
ray 2400, 1800
png {pdb_id}_{chain_id}_epitope_predictions.png, dpi=300

# =========================================================================
# LEGEND
# =========================================================================
# Firebrick: Very high confidence (>= 0.8)
# Red:       High confidence (0.7-0.8)
# Orange:    Medium-high confidence (0.6-0.7)
# Yellow:    Medium confidence (0.5-0.6)
# Palegreen: Low-medium confidence (0.4-0.5)
# Lightblue: Low confidence (0.3-0.4)
# Gray:      Very low confidence (< 0.3)
#
# To show ground truth: uncomment the ground_truth section above

print ""
print "====================================="
print "Visualization loaded successfully!"
print "====================================="
print "Rotate: Left-click + drag"
print "Zoom: Scroll wheel"
print "Ray trace: Type 'ray' in command line"
print ""
'''

    with open(output_path, 'w') as f:
        f.write(script)
    
    return output_path


def create_bfactor_script(df_stats, pdb_id, chain_id, output_path):
    """
    Generate a PyMOL script that colors by B-factor for smooth gradient.
    """
    script = f'''# =========================================================================
# B-Factor Gradient Coloring Script
# PDB: {pdb_id.upper()}, Chain: {chain_id}
# =========================================================================

reinitialize
fetch {pdb_id}, async=0
remove solvent
remove hetatm

bg_color white

# --- SETUP ---
hide everything
show cartoon, chain {chain_id}

# Reset all B-factors
alter chain {chain_id}, b=0

# --- SET B-FACTORS FROM PREDICTION SCORES ---
'''
    
    for _, row in df_stats.iterrows():
        res_id = str(row['res_id']).strip()
        # Scale score to 0-100 range
        score = row['prediction_score'] * 100
        script += f"alter chain {chain_id} and resi {res_id}, b={score:.2f}\n"
    
    script += f'''
# --- COLOR BY B-FACTOR ---
# Blue (low) -> White (medium) -> Red (high)
spectrum b, blue_white_red, chain {chain_id}, minimum=0, maximum=100

# Alternative coloring schemes (uncomment one):
# spectrum b, rainbow, chain {chain_id}, minimum=0, maximum=100
# spectrum b, cyan_white_magenta, chain {chain_id}, minimum=0, maximum=100

# --- FINALIZE ---
orient chain {chain_id}
zoom chain {chain_id}

# Optional: Show surface
# show surface, chain {chain_id}
# set transparency, 0.3

ray 2400, 1800
png {pdb_id}_{chain_id}_bfactor_gradient.png, dpi=300

print ""
print "Gradient coloring complete!"
print "Blue = Low prediction score"
print "White = Medium prediction score"  
print "Red = High prediction score"
print ""
'''
    
    with open(output_path, 'w') as f:
        f.write(script)
    
    return output_path


def create_chimera_script(df_stats, pdb_id, chain_id, output_path):
    """
    Generate a UCSF Chimera script for visualization (alternative to PyMOL).
    """
    script = f'''# =========================================================================
# Epitope Prediction Visualization - Chimera Script
# PDB: {pdb_id.upper()}, Chain: {chain_id}
# =========================================================================

# Open structure from PDB
open https://files.rcsb.org/download/{pdb_id.upper()}.pdb

# Remove waters and hide non-chain atoms
~display
display :{chain_id}
~display solvent
ribbon :{chain_id}
~ribbon ~:{chain_id}

# Set background
set bg_color white

# Base color
color gray :{chain_id}

'''
    
    # High confidence predictions
    high_conf = df_stats[df_stats['prediction_score'] >= 0.7]['res_id'].tolist()
    if high_conf:
        res_str = ','.join([str(r).strip() for r in high_conf])
        script += f"# High confidence (>= 0.7)\n"
        script += f"color red :{res_str}.{chain_id}\n"
        script += f"display :{res_str}.{chain_id}\n\n"
    
    # Medium-high confidence
    med_high = df_stats[(df_stats['prediction_score'] >= 0.5) & 
                        (df_stats['prediction_score'] < 0.7)]['res_id'].tolist()
    if med_high:
        res_str = ','.join([str(r).strip() for r in med_high])
        script += f"# Medium confidence (0.5-0.7)\n"
        script += f"color orange :{res_str}.{chain_id}\n\n"
    
    script += f'''
# Focus on chain
focus :{chain_id}

# Save image
copy file {pdb_id}_{chain_id}_chimera.png png dpi 300

'''
    
    with open(output_path, 'w') as f:
        f.write(script)
    
    return output_path


def create_visualization_plots(df_stats, pdb_id, chain_id, output_dir):
    """
    Create various visualization plots for the predictions.
    """
    fig, axes = plt.subplots(2, 2, figsize=(14, 12))
    
    # Plot 1: Score distribution histogram
    ax1 = axes[0, 0]
    ax1.hist(df_stats['prediction_score'], bins=50, edgecolor='black', alpha=0.7, color='steelblue')
    ax1.axvline(x=0.5, color='r', linestyle='--', linewidth=2, label='Threshold 0.5')
    ax1.axvline(x=0.6, color='orange', linestyle='--', linewidth=2, label='Threshold 0.6')
    ax1.axvline(x=0.7, color='darkred', linestyle='--', linewidth=2, label='Threshold 0.7')
    ax1.set_xlabel('Prediction Score', fontsize=12)
    ax1.set_ylabel('Number of Residues', fontsize=12)
    ax1.set_title(f'Distribution of Epitope Prediction Scores\n{pdb_id.upper()} Chain {chain_id}', fontsize=14)
    ax1.legend(loc='upper right')
    ax1.grid(alpha=0.3)
    
    # Plot 2: Score by epitope status
    ax2 = axes[0, 1]
    epitope_scores = df_stats[df_stats['is_epitope'] == 1]['prediction_score']
    non_epitope_scores = df_stats[df_stats['is_epitope'] == 0]['prediction_score']
    
    ax2.hist(non_epitope_scores, bins=30, alpha=0.6, label=f'Non-Epitope (n={len(non_epitope_scores)})', 
             color='steelblue', edgecolor='black')
    ax2.hist(epitope_scores, bins=30, alpha=0.6, label=f'Epitope (n={len(epitope_scores)})', 
             color='crimson', edgecolor='black')
    ax2.set_xlabel('Prediction Score', fontsize=12)
    ax2.set_ylabel('Number of Residues', fontsize=12)
    ax2.set_title('Score Distribution by Ground Truth Label', fontsize=14)
    ax2.legend(loc='upper right')
    ax2.grid(alpha=0.3)
    
    # Plot 3: Score along sequence position
    ax3 = axes[1, 0]
    positions = range(len(df_stats))
    ax3.plot(positions, df_stats['prediction_score'], 'b-', alpha=0.7, linewidth=1)
    ax3.fill_between(positions, 0, df_stats['prediction_score'], alpha=0.3)
    ax3.axhline(y=0.5, color='r', linestyle='--', label='Threshold 0.5')
    ax3.axhline(y=0.6, color='orange', linestyle='--', label='Threshold 0.6')
    
    # Mark ground truth epitopes
    gt_positions = [i for i, v in enumerate(df_stats['is_epitope']) if v == 1]
    gt_scores = df_stats.iloc[gt_positions]['prediction_score']
    ax3.scatter(gt_positions, gt_scores, c='red', s=30, label='Ground Truth Epitopes', zorder=5, alpha=0.7)
    
    ax3.set_xlabel('Residue Position', fontsize=12)
    ax3.set_ylabel('Prediction Score', fontsize=12)
    ax3.set_title('Prediction Score Along Sequence', fontsize=14)
    ax3.legend(loc='upper right')
    ax3.set_xlim(0, len(df_stats))
    ax3.set_ylim(0, 1)
    ax3.grid(alpha=0.3)
    
    # Plot 4: Summary statistics
    ax4 = axes[1, 1]
    ax4.axis('off')
    
    # Calculate statistics
    total = len(df_stats)
    gt_epitopes = df_stats['is_epitope'].sum()
    pred_05 = (df_stats['prediction_score'] >= 0.5).sum()
    pred_06 = (df_stats['prediction_score'] >= 0.6).sum()
    pred_07 = (df_stats['prediction_score'] >= 0.7).sum()
    
    # True positives at different thresholds
    tp_05 = ((df_stats['prediction_score'] >= 0.5) & (df_stats['is_epitope'] == 1)).sum()
    tp_06 = ((df_stats['prediction_score'] >= 0.6) & (df_stats['is_epitope'] == 1)).sum()
    tp_07 = ((df_stats['prediction_score'] >= 0.7) & (df_stats['is_epitope'] == 1)).sum()
    
    stats_text = f'''
    PREDICTION SUMMARY
    ==================
    
    PDB ID: {pdb_id.upper()}
    Chain: {chain_id}
    
    RESIDUE COUNTS:
    ---------------
    Total residues: {total}
    Ground truth epitopes: {gt_epitopes} ({100*gt_epitopes/total:.1f}%)
    
    PREDICTIONS BY THRESHOLD:
    -------------------------
    Score >= 0.5: {pred_05} residues ({100*pred_05/total:.1f}%)
    Score >= 0.6: {pred_06} residues ({100*pred_06/total:.1f}%)
    Score >= 0.7: {pred_07} residues ({100*pred_07/total:.1f}%)
    
    TRUE POSITIVES (predicted & actually epitope):
    ----------------------------------------------
    Threshold 0.5: {tp_05}/{gt_epitopes} = {100*tp_05/gt_epitopes:.1f}% recall
    Threshold 0.6: {tp_06}/{gt_epitopes} = {100*tp_06/gt_epitopes:.1f}% recall
    Threshold 0.7: {tp_07}/{gt_epitopes} = {100*tp_07/gt_epitopes:.1f}% recall
    
    SCORE STATISTICS:
    -----------------
    Mean score: {df_stats['prediction_score'].mean():.3f}
    Median score: {df_stats['prediction_score'].median():.3f}
    Max score: {df_stats['prediction_score'].max():.3f}
    Min score: {df_stats['prediction_score'].min():.3f}
    '''
    
    ax4.text(0.05, 0.95, stats_text, transform=ax4.transAxes, fontsize=11,
             verticalalignment='top', fontfamily='monospace',
             bbox=dict(boxstyle='round', facecolor='lightgray', alpha=0.3))
    
    plt.tight_layout()
    
    plot_path = os.path.join(output_dir, f'{pdb_id}_{chain_id}_analysis_plots.png')
    plt.savefig(plot_path, dpi=150, bbox_inches='tight')
    plt.close()
    
    return plot_path


def visualize_structure(pdb_id, chain_id=None, output_dir='visualization_output'):
    """
    Main function to generate all visualization files for a given structure.
    """
    print("\n" + "=" * 70)
    print(f"  EPITOPE PREDICTION VISUALIZATION")
    print("=" * 70)
    
    # Create output directory
    os.makedirs(output_dir, exist_ok=True)
    
    # Load protein data
    print(f"\n[1/5] Loading data for {pdb_id.upper()}...")
    protein_data = load_protein_data(pdb_id)
    
    if protein_data is None:
        print(f"\nError: Protein {pdb_id} not found in the dataset.")
        print("\nTo visualize this structure, you need to:")
        print("  1. Run inference on the PDB file using inference.py or predict_standalone.py")
        print(f"  2. Example: python inference.py {pdb_id}.pdb A")
        
        # List some available PDBs
        with open(config.STRUCTURED_DATA_PATH, 'rb') as f:
            protein_data_list = pickle.load(f)
        
        print(f"\nAvailable PDB IDs in dataset (first 30):")
        pdbs = [p['pdb_id'] for p in protein_data_list[:30]]
        print("  " + ", ".join(pdbs))
        return None
    
    # Detect chain if not provided
    df_stats = protein_data['df_stats'].copy()
    if chain_id is None:
        if 'chain' in df_stats.columns:
            chain_id = df_stats['chain'].iloc[0]
        else:
            chain_id = 'A'
        print(f"  Auto-detected chain: {chain_id}")
    
    # Get predictions
    print(f"[2/5] Running predictions...")
    pred_probas = get_predictions(protein_data)
    df_stats['prediction_score'] = pred_probas
    df_stats['pdb_id'] = pdb_id
    
    # Print summary
    print(f"\n  Structure: {pdb_id.upper()} Chain {chain_id}")
    print(f"  Total residues: {len(df_stats)}")
    print(f"  Ground truth epitopes: {df_stats['is_epitope'].sum()}")
    print(f"  Predicted epitopes (>= 0.6): {(pred_probas >= 0.6).sum()}")
    
    # Save predictions CSV
    print(f"\n[3/5] Saving predictions to CSV...")
    csv_path = os.path.join(output_dir, f'{pdb_id}_{chain_id}_predictions.csv')
    df_stats.to_csv(csv_path, index=False)
    print(f"  Saved: {csv_path}")
    
    # Generate PyMOL scripts
    print(f"[4/5] Generating visualization scripts...")
    
    pymol_path = os.path.join(output_dir, f'{pdb_id}_{chain_id}_visualization.pml')
    create_pymol_script(df_stats, pdb_id, chain_id, pymol_path)
    print(f"  PyMOL script: {pymol_path}")
    
    bfactor_path = os.path.join(output_dir, f'{pdb_id}_{chain_id}_bfactor.pml')
    create_bfactor_script(df_stats, pdb_id, chain_id, bfactor_path)
    print(f"  B-factor script: {bfactor_path}")
    
    chimera_path = os.path.join(output_dir, f'{pdb_id}_{chain_id}_chimera.cmd')
    create_chimera_script(df_stats, pdb_id, chain_id, chimera_path)
    print(f"  Chimera script: {chimera_path}")
    
    # Generate plots
    print(f"[5/5] Generating analysis plots...")
    plot_path = create_visualization_plots(df_stats, pdb_id, chain_id, output_dir)
    print(f"  Plots: {plot_path}")
    
    # Print top predictions
    print("\n" + "-" * 70)
    print("TOP 15 HIGHEST-SCORING RESIDUES:")
    print("-" * 70)
    top_15 = df_stats.nlargest(15, 'prediction_score')[['res_id', 'residue', 'prediction_score', 'is_epitope', 'rsa']]
    print(top_15.to_string(index=False))
    
    print("\n" + "=" * 70)
    print("  VISUALIZATION COMPLETE!")
    print("=" * 70)
    print(f"""
  Output files saved to: {output_dir}/
  
  To visualize in PyMOL:
    pymol {pymol_path}
    
  For smooth gradient coloring:
    pymol {bfactor_path}
    
  For UCSF Chimera:
    chimera {chimera_path}
  
  What to look for:
  - Red/orange regions indicate predicted epitopes
  - Compare with known functional regions (e.g., RBD for spike proteins)
  - High-scoring regions should be surface-exposed (high RSA)
""")
    
    return df_stats


def list_available_structures():
    """List structures available in the dataset."""
    print("\n" + "=" * 70)
    print("  AVAILABLE STRUCTURES IN DATASET")
    print("=" * 70)
    
    with open(config.STRUCTURED_DATA_PATH, 'rb') as f:
        protein_data_list = pickle.load(f)
    
    # Group by split
    with open(config.SPLITS_FILE_PATH, 'r') as f:
        splits = json.load(f)
    
    train_set = set(splits.get('train', []))
    val_set = set(splits.get('val', []))
    test_set = set(splits.get('test', []))
    
    print(f"\nTotal structures: {len(protein_data_list)}")
    print(f"Training set: {len(train_set)}")
    print(f"Validation set: {len(val_set)}")
    print(f"Test set: {len(test_set)}")
    
    print("\n--- Test Set Structures (first 50) ---")
    for i, pdb_id in enumerate(list(test_set)[:50]):
        print(f"  {pdb_id}", end="")
        if (i + 1) % 10 == 0:
            print()
    print()
    
    return list(protein_data_list)


def main():
    parser = argparse.ArgumentParser(
        description="Generate 3D visualization files for epitope predictions",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python visualize_epitope_predictions.py 6vxx A
  python visualize_epitope_predictions.py 7bnn S  
  python visualize_epitope_predictions.py 9e21
  python visualize_epitope_predictions.py --list
        """
    )
    
    parser.add_argument('pdb_id', nargs='?', type=str, 
                        help='PDB identifier (e.g., 6vxx, 7bnn)')
    parser.add_argument('chain_id', nargs='?', type=str, default=None,
                        help='Chain ID (default: auto-detect)')
    parser.add_argument('--output-dir', '-o', type=str, default='visualization_output',
                        help='Output directory (default: visualization_output)')
    parser.add_argument('--list', '-l', action='store_true',
                        help='List available structures in the dataset')
    
    args = parser.parse_args()
    
    if args.list:
        list_available_structures()
        return
    
    if args.pdb_id is None:
        parser.print_help()
        print("\n\nNo PDB ID provided. Use --list to see available structures.")
        return
    
    visualize_structure(args.pdb_id, args.chain_id, args.output_dir)


if __name__ == '__main__':
    main()
