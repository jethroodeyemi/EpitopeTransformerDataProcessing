"""
Standalone 3D Visualization Script for Epitope Predictions

This script generates visualization files for mapping epitope predictions onto
any protein structure that exists in your dataset.

Usage:
    python visualize_epitope_predictions.py <pdb_id> [chain_id]
    
Examples:
    python visualize_epitope_predictions.py 6vxx A
    python visualize_epitope_predictions.py 7bnn S
    python visualize_epitope_predictions.py 9e21    # Auto-detect chain

The script generates:
1. CSV file with per-residue prediction scores
2. PyMOL visualization script (.pml) for 3D viewing
3. PyMOL B-factor coloring script for smooth gradients
4. Chimera visualization script (.cmd) as alternative
5. Prediction score distribution plots

For SARS-CoV-2 RBD visualization:
- Look for red-colored regions on the structure
- The RBD should "light up" even if labeled negative in the training data
- This validates biological relevance beyond dataset labels
"""

